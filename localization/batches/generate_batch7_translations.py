def main():
    with open(BATCH7_PATH, "r", encoding="utf-8") as f:
        src_data = json.load(f)

    src_items = src_data["items"]
    assert len(src_items) == 58, f"Expected 58 items, got {len(src_items)}"

    locales = ["deDE", "esES", "esMX", "frFR", "itIT", "ptBR", "ruRU", "koKR", "zhCN", "zhTW"]
    total_generated = 0

    for loc in locales:
        loc_dict = TRANSLATIONS.get(loc, {})
        assert len(loc_dict) == 58, f"Locale {loc} has {len(loc_dict)} translations, expected 58"

        translated_items = []
        errors = 0

        for item in src_items:
            sid = item["id"]
            src = item["source"]
            sig = item["signature"]

            if src not in loc_dict:
                print(f"[{loc}] Missing translation for source: {src}")
                errors += 1
                continue

            tgt = loc_dict[src]

            # Invariant 1: Format Specifier Signature Parity
            tgt_sig = extract_signature(tgt)
            if sig != tgt_sig:
                print(f"[{loc}] SIGNATURE MISMATCH for id {sid}: '{src}' -> '{tgt}' (src sig='{sig}', tgt sig='{tgt_sig}')")
                errors += 1

            # Invariant 2: Color tag balance
            if not check_color_balance(src, tgt):
                print(f"[{loc}] COLOR CODE UNBALANCE for id {sid}: '{src}' -> '{tgt}'")
                errors += 1

            translated_items.append({
                "id": sid,
                "source": src,
                "target": tgt
            })

        if errors > 0:
            print(f"FAILED for locale {loc} with {errors} errors.")
            sys.exit(1)

        out_file = os.path.join(BATCHES_DIR, f"translated_{loc}_batch7.json")
        with open(out_file, "w", encoding="utf-8") as out_f:
            json.dump({
                "batch_id": 7,
                "locale": loc,
                "count": len(translated_items),
                "items": translated_items
            }, out_f, indent=2, ensure_ascii=False)

        print(f"✓ Generated {out_file} ({len(translated_items)} items, 0 errors)")
        total_generated += 1

    print(f"\nAll {total_generated} locale files generated and validated successfully!")

if __name__ == "__main__":
    main()
