def main():
    batch_file = os.path.join(os.path.dirname(__file__), "batch1b_ui_navigation.json")
    out_file = os.path.join(os.path.dirname(__file__), "translated_ruRU_batch1b.json")

    with open(batch_file, "r", encoding="utf-8") as f:
        batch_data = json.load(f)

    items = batch_data.get("items", [])
    print(f"Batch 1b items loaded: {len(items)}")

    errors = 0
    missing = 0
    output_items = []

    for item in items:
        source = item["source"]
        if source not in TRANSLATIONS_RURU:
            print(f"MISSING: {repr(source)}")
            missing += 1
            continue

        target = TRANSLATIONS_RURU[source]

        # 1. Format specifiers check
        sig_k = extract_signature(source)
        sig_v = extract_signature(target)
        if sig_k != sig_v:
            print(f"SIGNATURE MISMATCH: '{source}' -> '{target}' ({sig_k} != {sig_v})")
            errors += 1

        # 2. Color tags check
        if not check_color_balance(source, target):
            print(f"COLOR UNBALANCED: '{source}' -> '{target}'")
            errors += 1

        output_items.append({
            "source": source,
            "target": target
        })

    print(f"Validation complete: missing={missing}, errors={errors}")
    if missing > 0 or errors > 0:
        print("Aborting file generation due to validation errors.")
        sys.exit(1)

    with open(out_file, "w", encoding="utf-8") as f:
        json.dump({"items": output_items}, f, ensure_ascii=False, indent=2)

    print(f"Successfully wrote {len(output_items)} translated entries to {out_file}")

if __name__ == "__main__":
    main()
