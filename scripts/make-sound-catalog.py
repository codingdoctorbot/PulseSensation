#!/usr/bin/env python3
"""Regenerate Kapow/SoundCatalog.lua from the sound files in Kapow/Sounds/<pool>/.

WoW addons cannot list a folder, so the sounds the addon offers have to be spelled out in
Lua. Drop generated .ogg or .mp3 files into a pool folder (see
Kapow/Generation/generationpromptdatabase.md for what each pool wants), then run:

    python3 scripts/make-sound-catalog.py

Each folder Kapow/Sounds/<pool>/ becomes the pool "random:<pool>". A pool that shares its id
with a built-in game-sound pool in Display.lua (fightstart, victory, alert) joins it. An
optional label.txt in the folder gives the pool its name in the window; otherwise the folder
name is used. Files are listed in name order. Other file types are reported and skipped.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOUNDS = ROOT / "Kapow" / "Sounds"
OUT = ROOT / "Kapow" / "SoundCatalog.lua"
PLAYABLE = {".ogg", ".mp3"}

HEADER = """-- KAPOW — SoundCatalog.lua
--
-- GENERATED by scripts/make-sound-catalog.py from the files in Kapow/Sounds/<pool>/. Do not
-- edit by hand: drop .ogg or .mp3 files into a pool folder and run the script again.
--
-- Each pool becomes a "Random: ..." sound choice; a pool that shares its id with one of
-- Display.lua's built-in game-sound pools (fightstart, victory, alert) joins it instead.
-- What to generate for each pool: Kapow/Generation/generationpromptdatabase.md.

local _, ns = ...

-- pool id -> { label = "...", files = { "Interface\\\\AddOns\\\\Kapow\\\\Sounds\\\\<pool>\\\\<file>", ... } }
"""


def lua_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    pools = []
    skipped = []
    if SOUNDS.is_dir():
        for folder in sorted(p for p in SOUNDS.iterdir() if p.is_dir() and not p.name.startswith(".")):
            files = []
            for f in sorted(folder.iterdir()):
                if f.is_file() and f.suffix.lower() in PLAYABLE:
                    files.append(f"Interface\\AddOns\\Kapow\\Sounds\\{folder.name}\\{f.name}")
                elif f.is_file() and f.name not in ("label.txt", ".DS_Store"):
                    skipped.append(str(f.relative_to(ROOT)))
            if files:
                label_file = folder / "label.txt"
                label = label_file.read_text(encoding="utf-8").strip() if label_file.is_file() else folder.name
                pools.append((folder.name, label, files))

    lines = [HEADER, "ns.SOUND_FILES = {"]
    for pool_id, label, files in pools:
        lines.append(f"\t[{lua_string(pool_id)}] = {{ label = {lua_string(label)}, files = {{")
        for path in files:
            lines.append(f"\t\t{lua_string(path)},")
        lines.append("\t} },")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    total = sum(len(f) for _, _, f in pools)
    print(f"{OUT.relative_to(ROOT)}: {len(pools)} pools, {total} files")
    for path in skipped:
        print(f"skipped (not .ogg/.mp3): {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
