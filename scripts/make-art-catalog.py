#!/usr/bin/env python3
"""Regenerate Kapow/ArtCatalog.lua from Art/_metadata/manifest.json and Art/_fonts.

WoW addons cannot list a folder, so the art catalog the addon offers has to be spelled out
in Lua. Run this after adding art (a new category or message) to the manifest:

    python3 scripts/make-art-catalog.py

It also copies what the addon loads (the listed TGA frames, and each display font with its
OFL.txt license) from Art/ into Kapow/Art, so the addon folder is self-contained. Art/
stays the master copy with the sources, previews and metadata. Files already identical are
skipped; files in Kapow/Art that the catalog no longer lists are reported, not deleted.

Every listed frame is checked on disk: an uncompressed or RLE true-colour TGA, 32 bits per
pixel, power-of-two sides. A message with a missing or unusable frame is left out of the
catalog and reported. The display fonts in Art/_fonts (font-index.json, category-fonts.json)
are checked to be TrueType files and listed with the category each one belongs to. The exit
status is 1 when anything was left out.
"""

import filecmp
import json
import shutil
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "Art"
MANIFEST = ART / "_metadata" / "manifest.json"
FONT_INDEX = ART / "_fonts" / "font-index.json"
CATEGORY_FONTS = ART / "_fonts" / "category-fonts.json"
OUT = ROOT / "Kapow" / "ArtCatalog.lua"
CREDITS = ROOT / "Kapow" / "FONT-CREDITS.md"
ADDON_ART = ROOT / "Kapow" / "Art"

# Labels the window shows. The folders keep plain ids; the names players see are the
# addon's own, not borrowed game titles.
LABELS = {
    "arcade": "Roadfighter",
    "ninja": "Shadow Clan",
    "arena": "Boomer Shooter",
    "tactical": "Strike Squad",
    "football": "Soccer League",
}


def label(category):
    return LABELS.get(category, category.replace("-", " ").title())


def check_tga(path):
    """Return None when the file is usable, else the reason it is not."""
    if not path.is_file():
        return "missing"
    header = path.read_bytes()[:18]
    if len(header) < 18:
        return "truncated header"
    image_type = header[2]
    width, height = struct.unpack("<HH", header[12:16])
    bpp = header[16]
    if image_type not in (2, 10):
        return f"image type {image_type} (want true-colour 2 or 10)"
    if bpp != 32:
        return f"{bpp} bits per pixel (want 32 with alpha)"
    for side in (width, height):
        if side == 0 or side & (side - 1):
            return f"{width}x{height} is not power-of-two"
    return None


def check_ttf(path):
    """Return None when the file is a TrueType font, else the reason it is not."""
    if not path.is_file():
        return "missing"
    magic = path.read_bytes()[:4]
    if magic not in (b"\x00\x01\x00\x00", b"true"):
        return f"not a TrueType file (starts {magic!r})"
    return None


def wow_path(relative):
    """Art-relative path -> the path the client loads, through the Kapow/Art link."""
    return "Interface\\AddOns\\Kapow\\Art\\" + relative.replace("/", "\\")


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def sync_addon_art(relative_paths):
    """Copy Art/<path> to Kapow/Art/<path> for every path; returns (copied, stale)."""
    if ADDON_ART.is_symlink():
        raise SystemExit(f"{ADDON_ART} is a symlink; replace it with a folder first")
    copied = 0
    wanted = set()
    for rel in sorted(relative_paths):
        src, dst = ART / rel, ADDON_ART / rel
        wanted.add(dst.resolve())
        if dst.is_file() and filecmp.cmp(src, dst, shallow=False):
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        copied += 1
    stale = sorted(
        str(f.relative_to(ADDON_ART)) for f in ADDON_ART.rglob("*") if f.is_file() and f.resolve() not in wanted
        and f.name != ".DS_Store"
    )
    return copied, stale


def write_credits(credits):
    out = [
        "# Font credits",
        "",
        "KAPOW's display fonts are the work of the designers below, used unmodified under the",
        "[SIL Open Font License, Version 1.1](https://openfontlicense.org). Each font's full license and",
        "copyright notice ship beside it in `Art/_fonts/<font>/OFL.txt`; keep them with the font files",
        "whenever the addon is shared. The fonts are not covered by KAPOW's own license and are not",
        "sold separately. Sources are pinned to one commit of the official Google Fonts repository.",
        "",
        "This file is generated by `scripts/make-art-catalog.py` from `Art/_fonts/font-index.json`.",
        "",
        "| Font | Copyright | License | Used for | Source |",
        "|:---|:---|:---|:---|:---|",
    ]
    for family, notice, license_name, license_file, source, used_by in credits:
        notice_md = notice.replace("|", "\\|")
        out.append(
            f"| {family} | {notice_md} | {license_name} (`Art/{license_file}`) | {', '.join(used_by)} | [google/fonts]({source}) |"
        )
    out.append("")
    CREDITS.write_text("\n".join(out))


def main():
    manifest = json.loads(MANIFEST.read_text())
    words = {asset["key"]: asset["word"] for asset in manifest["assets"]}
    frames = {asset["key"]: asset["frames"] for asset in manifest["assets"]}

    problems = []
    usable = {}
    for key, files in frames.items():
        reasons = [f"{name}: {why}" for name in files if (why := check_tga(ART / name))]
        if len(files) != 3:
            reasons.append(f"{len(files)} frames (want 3)")
        if reasons:
            problems.append(f"{key}: " + "; ".join(reasons))
        else:
            usable[key] = True

    fonts, category_font, credits = [], {}, []
    font_files = []
    if FONT_INDEX.is_file() and CATEGORY_FONTS.is_file():
        index = json.loads(FONT_INDEX.read_text())["fonts"]
        assigned = json.loads(CATEGORY_FONTS.read_text())
        by_file = {}
        for key, info in index.items():
            why = check_ttf(ART / info["file"])
            if why:
                problems.append(f"font {key}: {info['file']}: {why}")
                continue
            used_by = [label(cat) for cat, a in assigned.items() if a["file"] == info["file"]]
            fonts.append((key, f"{info['family']} ({', '.join(used_by) or 'unassigned'})", wow_path(info["file"])))
            notice = " ".join(info["copyright_notice"].split())
            credits.append((info["family"], notice, info["license"], info["license_file"], info["upstream_directory"], used_by))
            by_file[info["file"]] = key
            font_files += [info["file"], info["license_file"]]
        for cat, a in assigned.items():
            if a["file"] in by_file:
                category_font[cat] = by_file[a["file"]]

    lines = [
        "-- KAPOW — ArtCatalog.lua",
        "--",
        "-- GENERATED by scripts/make-art-catalog.py from Art/_metadata/manifest.json. Do not edit;",
        "-- add art to the manifest and run the script again.",
        "",
        "local _, ns = ...",
        "",
        "ns.ART_CATALOG = {",
    ]
    for category, keys in manifest["categories"].items():
        items = [key for key in keys if key in usable]
        if not items:
            continue
        font = f", font = {lua_string(category_font[category])}" if category in category_font else ""
        lines.append(f"\t{{ id = {lua_string(category)}, label = {lua_string(label(category))}{font}, items = {{")
        for key in items:
            lines.append(f"\t\t{{ {lua_string(key)}, {lua_string(words[key])} }},")
        lines.append("\t} },")
    lines.append("}")
    lines.append("")
    lines.append("-- Display fonts from Art/_fonts (SIL Open Font License 1.1, licenses beside each file).")
    lines.append("ns.ART_FONTS = {")
    for key, text, path in fonts:
        lines.append(f"\t{{ {lua_string(key)}, {lua_string(text)}, {lua_string(path)} }},")
    lines.append("}")
    lines.append("")
    lines.append("-- Font attributions, shown by /kapow credits. Generated from Art/_fonts/font-index.json.")
    lines.append("ns.FONT_CREDITS = {")
    for family, notice, license_name, _, _, _ in credits:
        lines.append(f"\t{{ {lua_string(family)}, {lua_string(notice)}, {lua_string(license_name)} }},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    write_credits(credits)

    files = [name for key in usable for name in frames[key]] + font_files
    copied, stale = sync_addon_art(files)
    print(f"Kapow/Art: {len(files)} files needed, {copied} copied")
    for name in stale:
        print("not in the catalog (left in place):", name, file=sys.stderr)

    total = sum(1 for keys in manifest["categories"].values() for key in keys if key in usable)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(usable)} sequences, {total} category entries, {len(fonts)} fonts")
    for problem in problems:
        print("left out:", problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
